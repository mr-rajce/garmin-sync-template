"""Sample data and dashboard with made-up numbers, to show what the result looks like.

Usage:  python -m garmin_sync.sample --out docs/sample
Generates a year of fictional data for 2030 (fixed random seed, so the output is
stable), then writes the dashboard and the daily check from it. Nothing here comes
from a real person.
"""

from __future__ import annotations

import argparse
import math
import random
import tempfile
from datetime import date, timedelta
from pathlib import Path

from . import check, dashboard, journal, store

TODAY = date(2030, 10, 25)
DAYS = 400
SEED = 2030


def generate(data_dir: Path, today: date = TODAY, seed: int = SEED) -> journal.Journal:
    """Write a year of plausible fictional data into data_dir; return a matching journal."""
    rng = random.Random(seed)
    party = {today - timedelta(days=n) for n in (3, 17, 45, 80, 130)}
    ill = (today - timedelta(days=60), today - timedelta(days=54))
    entries: dict[date, journal.Entry] = {}
    for i in range(DAYS, 0, -1):
        day = today - timedelta(days=i)
        if rng.random() < 0.03:  # watch not worn: no files, a gap, not zero
            continue
        season = math.sin((day.timetuple().tm_yday / 365) * 2 * math.pi)
        # A party shows up in the next two nights (the daily check needs 2 days in a row).
        after_party = 1 if (day - timedelta(days=1)) in party else 0.6 if (day - timedelta(days=2)) in party else 0
        sick = ill[0] <= day <= ill[1]
        hrv = 55 + 6 * season + rng.gauss(0, 5) - 16 * after_party - (10 if sick else 0)
        sleep_h = 7.2 + rng.gauss(0, 0.6) - 1.3 * after_party
        score = max(20, min(98, 80 + (sleep_h - 7.2) * 9 + (hrv - 55) * 0.6 + rng.gauss(0, 4)))
        rhr = 48 - 0.08 * (hrv - 55) + rng.gauss(0, 1) + 5 * after_party + (4 if sick else 0)
        bb = max(15, min(100, 88 + (score - 80) * 0.8 + rng.gauss(0, 5)))
        stress = max(5, 24 + rng.gauss(0, 5) + (8 if day.weekday() < 5 else -4))
        steps = max(800, int(rng.gauss(9500, 2800) - (5000 if sick else 0)))
        iso = day.isoformat()
        store.write_if_changed(store.day_path(data_dir, "hrv", iso), {"calendarDate": iso, "lastNightAvg": round(hrv)})
        store.write_if_changed(store.day_path(data_dir, "sleep", iso), {
            "calendarDate": iso, "sleepTimeSeconds": round(sleep_h * 3600),
            "sleepScores": {"overall": {"value": round(score)}}})
        store.write_if_changed(store.day_path(data_dir, "daily_summary", iso), {
            "calendarDate": iso, "heartRate": {"restingValue": round(rhr)},
            "bodyBattery": {"maxValue": round(bb)}, "stress": {"avgLevel": round(stress)}})
        store.write_if_changed(store.day_path(data_dir, "steps", iso), {"calendarDate": iso, "totalSteps": steps})
        if day.weekday() in (1, 5) and not sick:
            run = day.weekday() == 1
            store.write_if_changed(store.activity_path(data_dir, iso, 1000 + i), {
                "activityId": 1000 + i, "startTimeLocal": f"{iso} {'18:10' if run else '09:30'}:00",
                "activityType": {"typeKey": "running" if run else "hiking"},
                "duration": rng.randint(30, 55) * 60 if run else rng.randint(120, 200) * 60,
                "distance": rng.uniform(5, 10) * 1000 if run else rng.uniform(8, 15) * 1000})
        if day in party:
            entries[day] = journal.Entry(["party", "alcohol"], "Sample entry.")
    periods = [journal.Period(ill[0], ill[1], "illness", "Sample: a cold.")]
    return journal.Journal(entries=entries, periods=periods)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=Path("docs/sample"))
    args = parser.parse_args(argv)
    with tempfile.TemporaryDirectory() as tmp:
        data_dir = Path(tmp)
        j = generate(data_dir)
        md = dashboard.build(data_dir, args.out, TODAY, j, guide="../charts.md")
        note = "> **Sample with made-up data** (fictional year 2030, generated by `python -m garmin_sync.sample`). Your own dashboard is `reports/dashboard.md`.\n\n"
        store.write_if_changed_text(args.out / "dashboard.md", note + md)
        for offset in range(30, -1, -1):
            day = TODAY - timedelta(days=offset)
            lines = [line for line in check.findings(data_dir, day, j) if not line.startswith("No daily summary")]
            if lines:
                check.record(args.out, day, lines)
    print(f"{args.out}/dashboard.md written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
